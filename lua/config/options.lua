local opt = vim.opt

----------------------------------------------------
-- Numbers
----------------------------------------------------

opt.number = true
opt.relativenumber = true

----------------------------------------------------
-- Tabs
----------------------------------------------------

opt.expandtab = true
opt.shiftwidth =4
opt.tabstop =4
opt.softtabstop =4

opt.smartindent = true

----------------------------------------------------
-- Search
----------------------------------------------------

opt.ignorecase = true
opt.smartcase = true

----------------------------------------------------
-- UI
----------------------------------------------------

opt.termguicolors = true

opt.cursorline = true

opt.signcolumn="yes"

opt.winborder = "rounded"

opt.wrap=false

opt.scrolloff=8

----------------------------------------------------
-- Splits
----------------------------------------------------

opt.splitbelow=true
opt.splitright=true

----------------------------------------------------
-- Clipboard
----------------------------------------------------

opt.clipboard="unnamedplus"

----------------------------------------------------
-- Mouse
----------------------------------------------------

opt.mouse="a"

----------------------------------------------------
-- Leader
----------------------------------------------------

vim.g.mapleader=" "
vim.g.maplocalleader="\\"
