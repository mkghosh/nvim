local M = {}

--------------------------------------------------------------------------------
-- Split
--------------------------------------------------------------------------------

function M.vsplit()
    vim.cmd.vsplit()
end

function M.split()
    vim.cmd.split()
end

--------------------------------------------------------------------------------
-- Close
--------------------------------------------------------------------------------

function M.close()
    vim.cmd.close()
end

function M.only()
    vim.cmd.only()
end

--------------------------------------------------------------------------------
-- Navigation
--------------------------------------------------------------------------------

function M.left()
    vim.cmd.wincmd("h")
end

function M.down()
    vim.cmd.wincmd("j")
end

function M.up()
    vim.cmd.wincmd("k")
end

function M.right()
    vim.cmd.wincmd("l")
end

--------------------------------------------------------------------------------
-- Resize
--------------------------------------------------------------------------------

function M.equalize()
    vim.cmd.wincmd("=")
end

return M
